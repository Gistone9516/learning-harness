# -*- coding: utf-8 -*-
"""HTTP handler of the gateway (specs/web-gateway.md §1, §3): login, subject index, host tree, API proxy.

Nothing here names a subject: slugs, folders, base path and title come from the config (GW-14).
"""
from __future__ import annotations

import http.client
import http.server
import json
import logging
import mimetypes
import select
import socket
import threading
import time
from pathlib import Path
from urllib.parse import parse_qs, quote, unquote, urlsplit

import auth
import pages
from config import Config, Subject

import hostfiles

log = logging.getLogger("gateway")

MAX_BODY = 4 * 1024 * 1024       # same bound as bot/ai_server.py _MAX_BODY
LOGIN_BODY = 4096                # GW-16
CLIENT_IDLE_S = 60               # GW-16: a client socket that sends nothing for this long is dropped
PROXY_TIMEOUT_S = 900            # generation can take minutes (GW-5)
_LOOPBACK = ("127.0.0.1", "::1")
_TYPES = {".js": "text/javascript; charset=utf-8", ".json": "application/json; charset=utf-8",
          ".css": "text/css; charset=utf-8", ".html": "text/html; charset=utf-8",
          ".md": "text/markdown; charset=utf-8", ".txt": "text/plain; charset=utf-8",
          ".svg": "image/svg+xml"}
_HOP = {"connection", "keep-alive", "transfer-encoding", "te", "trailer", "upgrade",
        "proxy-authorization", "proxy-authenticate"}


def client_gone(sock: socket.socket) -> bool:
    """True once the browser closed its side. The request body is already read, so readable means EOF or reset."""
    try:
        readable, _, _ = select.select([sock], [], [], 0)
        if not readable:
            return False
        return sock.recv(1, socket.MSG_PEEK) == b""
    except (OSError, ValueError):
        return True


def _abort(conn: http.client.HTTPConnection) -> None:
    sock = conn.sock
    if sock is not None:
        try:
            sock.shutdown(socket.SHUT_RDWR)
        except OSError:
            pass
    conn.close()


def content_type(path: Path) -> str:
    return _TYPES.get(path.suffix.lower()) or mimetypes.guess_type(path.name)[0] or "application/octet-stream"


def safe_next(base: str, nxt: str | None) -> str:
    """Only a path inside this gateway, in printable ASCII (it lands in the Location header, GW-15); anything else
    (another host, //x, a scheme, CR/LF, spaces, non-ASCII) falls back to the index."""
    if (nxt and nxt.startswith(base + "/") and not nxt.startswith("//") and "\\" not in nxt
            and all(33 <= ord(c) <= 126 for c in nxt)):
        return nxt
    return base + "/"


# GW-5: what a subject's pages call. Anything else, /repos/load included unless the subject allows it, is 404.
def api_allowed(subject: Subject, method: str, rest: str) -> bool:
    path = rest.split("?", 1)[0]
    if path == "/state" or path.startswith("/state/"):
        return method in ("GET", "PUT", "DELETE", "POST")
    if path in ("/health", "/sessions"):
        return method == "GET"
    if path in ("/ai", "/problems"):
        return method == "POST"
    if path == "/repos/load":
        return method == "POST" and subject.allow_repo_load
    return False


def runtime_config(cfg: Config, s: Subject) -> str:
    """local.config.js for the gateway (GW-3): where the API is, no token."""
    body = {"serverUrl": f"{cfg.base_path}/{s.slug}/api", "gated": True}
    return "// Generated by the gateway (specs/web-gateway.md GW-3). The token stays on the server.\n" \
           f"window.LH_LOCAL = {json.dumps(body)};\n"


def make_handler(cfg: Config, kit_dist: Path, throttle: auth.Throttle):
    base = cfg.base_path

    class Handler(http.server.BaseHTTPRequestHandler):
        server_version = "lh-gateway"
        sys_version = ""
        timeout = CLIENT_IDLE_S

        # ── small helpers ──────────────────────────────────────────────────────────
        def log_message(self, fmt, *args):  # the default line carries the query string (GW-13)
            pass

        def _log(self, status: int) -> None:
            path = urlsplit(self.path).path
            log.info("%s %s %d %.0fms", self.command, path, status, (time.monotonic() - self._t0) * 1000)

        def _secure(self) -> bool:
            visitor = self.headers.get("CF-Visitor", "")
            return "https" in visitor or self.headers.get("X-Forwarded-Proto", "").lower() == "https"

        def _client(self) -> str:
            peer = self.client_address[0]
            forwarded = self.headers.get("CF-Connecting-IP")
            return forwarded.strip() if peer in _LOOPBACK and forwarded else peer

        def _send(self, status: int, body: bytes, ctype: str, headers: dict[str, str] | None = None) -> None:
            self.send_response(status)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            for k, v in (headers or {}).items():
                self.send_header(k, v)
            for c in self._cookies:
                self.send_header("Set-Cookie", c)
            self.end_headers()
            if self.command != "HEAD":
                self.wfile.write(body)
            self._log(status)

        def _html(self, status: int, html: str, headers: dict[str, str] | None = None) -> None:
            self._send(status, html.encode("utf-8"), "text/html; charset=utf-8", headers)

        def _json(self, status: int, obj: dict) -> None:
            self._send(status, json.dumps(obj).encode("utf-8"), "application/json; charset=utf-8")

        def _redirect(self, status: int, location: str) -> None:
            self._send(status, b"", "text/plain; charset=utf-8", {"Location": location})

        def _body(self, limit: int = MAX_BODY) -> bytes | None:
            try:
                n = int(self.headers.get("Content-Length") or 0)
            except ValueError:
                return None
            if n < 0 or n > limit:
                return None
            return self.rfile.read(n) if n else b""

        def _signed_in(self) -> bool:
            ok, reissue = auth.check(cfg.auth.secret, auth.read_cookie(self.headers.get("Cookie")))
            if ok and reissue:
                self._cookies.append(auth.cookie_header(base, auth.issue(cfg.auth.secret, cfg.auth.session_days),
                                                        cfg.auth.session_days, self._secure()))
            return ok

        def _cross_origin(self) -> bool:
            origin = self.headers.get("Origin")
            if not origin or origin == "null":
                return bool(origin)
            return urlsplit(origin).netloc.lower() != (self.headers.get("Host") or "").lower()

        # ── dispatch ───────────────────────────────────────────────────────────────
        def _handle(self) -> None:
            self._t0 = time.monotonic()
            self._cookies: list[str] = []
            try:
                self._route()
            except (ConnectionError, TimeoutError, OSError):
                self.close_connection = True
            except Exception as e:  # GW-16: a malformed request must not take the worker down
                log.warning("bad request %s: %s", self.command, type(e).__name__)
                self._cookies = []
                try:
                    self._json(400, {"ok": False, "error": "bad request"})
                except OSError:
                    pass

        def _route(self) -> None:
            parts = urlsplit(self.path)
            path = unquote(parts.path)
            if path == base:
                return self._redirect(308, base + "/")
            if not path.startswith(base + "/"):
                return self._json(404, {"ok": False, "error": "not found"})
            rest = path[len(base):]
            if self.command not in ("GET", "HEAD") and self._cross_origin():
                return self._json(403, {"ok": False, "error": "cross-origin request refused"})

            if rest == "/health":
                return self._json(200, {"ok": True})
            if rest == "/login":
                return self._login(parts.query)
            if rest == "/logout" and self.command == "POST":
                self._cookies.append(auth.clear_cookie_header(base, self._secure()))
                return self._redirect(303, base + "/login")

            slug, _, sub = rest[1:].partition("/")
            subject = cfg.subject(slug) if slug else None
            is_api = subject is not None and (sub == "api" or sub.startswith("api/"))
            if not self._signed_in():
                if is_api:
                    return self._json(401, {"ok": False, "error": "login required"})
                nxt = parts.path + (("?" + parts.query) if parts.query else "")
                return self._redirect(303, f"{base}/login?next={quote(nxt, safe='')}")

            if rest == "/":
                return self._html(200, pages.index_page(cfg))
            if subject is None:
                return self._html(404, pages.not_found_page(cfg))
            if "/" not in rest[1:]:
                return self._redirect(308, f"{base}/{slug}/" + (("?" + parts.query) if parts.query else ""))
            if is_api:
                rest_api = sub[len("api"):] or "/"
                if not api_allowed(subject, self.command, rest_api):
                    return self._json(404, {"ok": False, "error": "not found"})
                return self._proxy(subject, rest_api, parts.query)
            if sub == "local.config.js":
                return self._send(200, runtime_config(cfg, subject).encode("utf-8"), "text/javascript; charset=utf-8")
            if self.command not in ("GET", "HEAD"):
                return self._json(405, {"ok": False, "error": "method not allowed"})
            target = hostfiles.resolve(subject.dir, kit_dist, sub)
            if target is None or not target.is_file():
                return self._json(404, {"ok": False, "error": "not found"})
            return self._send(200, target.read_bytes(), content_type(target))

        def _login(self, query: str) -> None:
            nxt = safe_next(base, (parse_qs(query).get("next") or [None])[0])
            if self.command in ("GET", "HEAD"):
                if self._signed_in():
                    return self._redirect(303, nxt)
                return self._html(200, pages.login_page(cfg, nxt))
            if self.command != "POST":
                return self._json(405, {"ok": False, "error": "method not allowed"})
            client = self._client()
            # GW-10: the attempt is counted before the check, so parallel guesses cannot slip under the limit.
            if not throttle.attempt(client):
                return self._html(429, pages.login_page(cfg, nxt, error="throttled"))
            body = self._body(LOGIN_BODY)
            form = parse_qs((body or b"").decode("utf-8", "replace"))
            password = (form.get("password") or [""])[0]
            nxt = safe_next(base, (form.get("next") or [nxt])[0])
            if body is None or not cfg.auth.password_hash or not auth.verify_password(password, cfg.auth.password_hash):
                log.warning("login failed from %s", client)
                return self._html(401, pages.login_page(cfg, nxt, error="wrong"))
            throttle.succeeded(client)
            self._cookies.append(auth.cookie_header(base, auth.issue(cfg.auth.secret, cfg.auth.session_days),
                                                    cfg.auth.session_days, self._secure()))
            return self._redirect(303, nxt)

        def _proxy(self, s: Subject, rest: str, query: str) -> None:
            body = self._body()
            if body is None:
                return self._json(413, {"ok": False, "error": "body too large"})
            headers = {k: v for k, v in self.headers.items()
                       if k.lower() in ("content-type", "accept", "accept-language")}
            headers["X-AI-Token"] = s.token       # GW-3: the incoming Authorization / X-AI-Token never pass
            headers["Content-Length"] = str(len(body))
            conn = http.client.HTTPConnection("127.0.0.1", s.ai_port, timeout=PROXY_TIMEOUT_S)
            out: dict = {}

            def call() -> None:
                try:
                    conn.request(self.command, rest + (("?" + query) if query else ""), body=body, headers=headers)
                    res = conn.getresponse()
                    out["data"], out["status"] = res.read(), res.status
                    out["ctype"] = res.getheader("Content-Type") or "application/json; charset=utf-8"
                except (OSError, http.client.HTTPException) as e:
                    out["error"] = e

            worker = threading.Thread(target=call, daemon=True)
            worker.start()
            # GW-5: while upstream works, watch the browser; if it leaves, close upstream so ai_server ends claude.
            while worker.is_alive():
                worker.join(0.5)
                if worker.is_alive() and client_gone(self.connection):
                    log.info("%s %s client left; closing upstream", self.command, urlsplit(self.path).path)
                    _abort(conn)
                    worker.join(5)
                    self.close_connection = True
                    return
            conn.close()
            if "error" in out:
                return self._json(502, {"ok": False, "error": "ai_server unreachable"})
            return self._send(out["status"], out["data"], out["ctype"])

        def do_GET(self):
            self._handle()

        def do_HEAD(self):
            self._handle()

        def do_POST(self):
            self._handle()

        def do_PUT(self):
            self._handle()

        def do_DELETE(self):
            self._handle()

        def do_OPTIONS(self):
            # Same origin only: the page and the API share one origin, so no preflight is ever needed.
            self._t0 = time.monotonic()
            self._cookies = []
            self._json(405, {"ok": False, "error": "method not allowed"})

    return Handler
